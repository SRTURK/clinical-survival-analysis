library(survival)
raw <- survival::colon
input_snapshot(raw,'colon','survival')
check('source rows',nrow(raw)==1858,nrow(raw))
check('patient endpoint key unique',!anyDuplicated(raw[c('id','etype')]))
check('two endpoint records per patient',all(table(raw$id)==2))
check('endpoint coding',setequal(unique(raw$etype),c(1,2)))
check('status is binary',all(raw$status %in% c(0,1)))
check('positive observed time',all(is.finite(raw$time)&raw$time>0))
death <- raw[raw$etype==2,]
check('one death record per patient',nrow(death)==929&&!anyDuplicated(death$id))
analysis <- droplevels(death[death$rx %in% config$primary_arms,])
analysis$rx <- factor(analysis$rx,levels=config$primary_arms)
check('two-arm analysis size',nrow(analysis)==619,nrow(analysis))
check('primary time status treatment complete',!anyNA(analysis[c('time','status','rx')]))
flow <- data.frame(stage=c('Endpoint records','Unique patients / death records','Excluded Lev-only arm','Primary two-arm population'),n=c(nrow(raw),nrow(death),sum(death$rx=='Lev'),nrow(analysis)))
save_table(flow,'analysis_flow')
save_table(analysis,'analysis_dataset')
missingness <- data.frame(variable=names(analysis),missing=sapply(analysis,function(x)sum(is.na(x))))
save_table(missingness,'missingness')
node_disagreement <- death[!is.na(death$nodes)&(death$node4!=as.integer(death$nodes>4)),c('id','nodes','node4')]
save_table(node_disagreement,'node_discrepancies')
save_table(baseline_table(analysis,'rx',c('age','nodes'),c('sex','extent','surg')),'table1_baseline')
cat('Two-arm population:',nrow(analysis),' deaths:',sum(analysis$status),' node inconsistencies in all patients:',nrow(node_disagreement),'\n')
